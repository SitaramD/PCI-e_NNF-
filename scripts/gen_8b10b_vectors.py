#!/usr/bin/env python3
"""
Generate tb/unit/tb_8b10b.sv with golden 8b/10b vectors.

The expected code groups come from an independent reference implementation
(pip install encdec8b10b), NOT from our RTL, so the testbench really checks
the encoder tables.

Usage:  python3 scripts/gen_8b10b_vectors.py > tb/unit/tb_8b10b.sv
"""
import random
from encdec8b10b import EncDec8B10B as E

K_CODES = [0x1C, 0x3C, 0x5C, 0x7C, 0x9C, 0xBC, 0xDC, 0xFC, 0xF7, 0xFB, 0xFD, 0xFE]

random.seed(1)
stim = [(0, d) for d in range(256)] + [(1, k) for k in K_CODES]
for _ in range(500):
    if random.random() < 0.1:
        stim.append((1, random.choice(K_CODES)))
    else:
        stim.append((0, random.randrange(256)))

rd = 0
exp = []
for k, d in stim:
    rd, code = E.enc_8b10b(d, rd, k)
    exp.append(code)

N = len(stim)
stim_s = ",\n    ".join(", ".join("9'h%03x" % ((k << 8) | d) for k, d in stim[i:i+8]) for i in range(0, N, 8))
exp_s  = ",\n    ".join(", ".join("10'h%03x" % c for c in exp[i:i+8]) for i in range(0, N, 8))

print(f"""`timescale 1ns/1ps
// =============================================================================
// tb_8b10b.sv  - unit test for pcie_8b10b_enc / pcie_8b10b_dec
// GENERATED by scripts/gen_8b10b_vectors.py - do not edit by hand.
//
//  1. Encoder output matches an independent reference for {N} symbols
//     (all 256 data bytes, all 12 K codes, 500 random) starting at RD-.
//  2. Decoder recovers every symbol with no code / disparity errors.
//  3. Serial stream never has more than 5 equal bits in a row, and the
//     running digital sum stays bounded (DC balance).
//  4. Decoder flags invalid code groups.
// =============================================================================
module tb_8b10b;
  localparam int N = {N};

  logic [8:0] stim [N] = '{{
    {stim_s}
  }};

  logic [9:0] expv [N] = '{{
    {exp_s}
  }};

  logic       clk = 1'b0, rst = 1'b1;
  always #2 clk = ~clk;

  logic [7:0] din, dout;
  logic       kin, kout, kerr, cerr, derr, den;
  logic [9:0] code, dec_in;

  pcie_8b10b_enc u_enc (.clk(clk), .rst(rst), .en(1'b1), .din(din), .kin(kin), .dout(code), .kerr(kerr));
  pcie_8b10b_dec u_dec (.clk(clk), .rst(rst), .en(den), .din(dec_in), .dout(dout), .kout(kout),
                        .code_err(cerr), .disp_err(derr));

  int errors = 0;
  int run_len = 0, rds = 0, max_rds = 0, min_rds = 0;
  logic last_bit = 1'b0;

  initial begin
    din = 8'h00; kin = 1'b0; den = 1'b0; dec_in = 10'h0;
    repeat (3) @(negedge clk);
    rst = 1'b0;

    // ---------------- encoder vs golden, decoder round trip ----------------
    for (int i = 0; i < N + 2; i++) begin
      if (i < N) begin
        kin = stim[i][8];
        din = stim[i][7:0];
      end
      @(negedge clk);
      // encoder output for stim[i] is visible one clock after it was applied
      if (i < N) begin
        if (code !== expv[i]) begin
          errors++;
          if (errors < 10) $display("ENC FAIL #%0d: K=%0d D=%02x got %03x exp %03x", i, stim[i][8], stim[i][7:0], code, expv[i]);
        end
        if (kerr) begin
          errors++;
          $display("ENC FAIL #%0d: unexpected kerr", i);
        end
        // serial checks (bit 0 first)
        for (int b = 0; b < 10; b++) begin
          if (code[b] == last_bit) run_len++; else run_len = 1;
          last_bit = code[b];
          rds += code[b] ? 1 : -1;
          if (run_len > 5) begin
            errors++;
            $display("RUN LENGTH FAIL at symbol %0d", i);
          end
          if (rds > max_rds) max_rds = rds;
          if (rds < min_rds) min_rds = rds;
        end
        dec_in = code;
        den    = 1'b1;
      end else begin
        den = 1'b0;
      end
      // decoder output for stim[i-1] (decoder adds one more clock)
      if (i >= 1 && (i - 1) < N) begin
        if (dout !== stim[i-1][7:0] || kout !== stim[i-1][8] || cerr || derr) begin
          errors++;
          if (errors < 10) $display("DEC FAIL #%0d: got K=%0d D=%02x cerr=%0d derr=%0d exp K=%0d D=%02x",
                                    i-1, kout, dout, cerr, derr, stim[i-1][8], stim[i-1][7:0]);
        end
      end
    end
    // 8b/10b has a digital sum variation of 6: the running sum stays in a 6-wide window
    $display("running digital sum range = [%0d, %0d]", min_rds, max_rds);
    if (max_rds - min_rds > 6) begin errors++; $display("DC balance FAIL"); end

    // ---------------- invalid code groups ----------------
    dec_in = 10'h000; den = 1'b1; @(negedge clk);
    den = 1'b0; @(negedge clk);
    if (!cerr) begin errors++; $display("DEC FAIL: 0x000 not flagged"); end
    dec_in = 10'h3FF; den = 1'b1; @(negedge clk);
    den = 1'b0; @(negedge clk);
    if (!cerr) begin errors++; $display("DEC FAIL: 0x3FF not flagged"); end

    // ---------------- invalid K request ----------------
    kin = 1'b1; din = 8'h00; @(negedge clk);
    if (!kerr) begin errors++; $display("ENC FAIL: K0.0 not flagged"); end

    if (errors == 0) $display("*** tb_8b10b PASSED (%0d symbols) ***", N);
    else             $display("*** tb_8b10b FAILED: %0d errors ***", errors);
    $finish;
  end
endmodule""")
